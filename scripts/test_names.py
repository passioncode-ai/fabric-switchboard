#!/usr/bin/env python3
"""The Rust test inventory (plan 2026-11-17, step A1): a test that existed must not disappear unseen.

`scripts/test-names.txt` lists every Rust test the workspace's test binaries declare, as
`<package> <kind>:<target> <test path>`, sorted. `--check` (run by `scripts/check.sh` right after
`cargo test`, whose binaries it reuses) fails when a recorded name is gone: a removed or renamed
test lands only with the list updated in the same change (`--write`), so the removal shows in the
diff. A name the list does not hold yet is reported and does not fail; `--write` records it.

The names are those of the machine the list was made on (`# os:`, macOS, where the gate runs): tests behind
`#[cfg(target_os = ...)]` differ between systems, so on another system `--check` says it was
skipped, and `--write` refuses there unless `--other-system` is given. Doc tests are not
listed.
"""
from __future__ import annotations

import argparse
import json
import os
import platform
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LIST = ROOT / "scripts" / "test-names.txt"
HEADER = (
    "# Every Rust test of the workspace's test binaries: <package> <kind>:<target> <test>.\n"
    "# Generated by `python3 scripts/test_names.py --write`; `scripts/check.sh` fails when a\n"
    "# name here is gone (plan 2026-11-17, step A1). Update it in the change that removes one.\n"
)


def system() -> str:
    return platform.system().lower()


def parse_list(output: str) -> list[str]:
    """Test names from a test binary's `--list --format terse` output (`name: test` lines)."""
    names = []
    for line in output.splitlines():
        if line.endswith(": test"):
            names.append(line[: -len(": test")])
    return names


def parse_file(text: str) -> tuple[str | None, set[str]]:
    """The `# os:` of a list and its names."""
    os_name, names = None, set()
    for line in text.splitlines():
        if line.startswith("# os:"):
            os_name = line[len("# os:") :].strip()
        elif line and not line.startswith("#"):
            names.add(line)
    return os_name, names


def render(os_name: str, names: set[str]) -> str:
    return HEADER + f"# os: {os_name}\n" + "".join(f"{n}\n" for n in sorted(names))


def compare(recorded: set[str], current: set[str]) -> tuple[list[str], list[str]]:
    """(gone, new): recorded names no binary declares now, and declared names not recorded."""
    return sorted(recorded - current), sorted(current - recorded)


def binaries(cargo: str = "cargo") -> list[tuple[str, Path, Path]]:
    """(prefix, executable, package dir) of every test binary `cargo test --workspace` builds."""
    meta = json.loads(
        subprocess.run(
            [cargo, "metadata", "--no-deps", "--format-version", "1", "--locked"],
            cwd=ROOT,
            check=True,
            capture_output=True,
            text=True,
        ).stdout
    )
    packages = {p["manifest_path"]: p["name"] for p in meta["packages"]}
    built = subprocess.run(
        [cargo, "test", "--workspace", "--locked", "--no-run", "--message-format=json"],
        cwd=ROOT,
        check=True,
        stdout=subprocess.PIPE,
        text=True,
    ).stdout
    found = []
    for line in built.splitlines():
        if not line.startswith("{"):
            continue
        message = json.loads(line)
        if message.get("reason") != "compiler-artifact" or not message.get("executable"):
            continue
        if not message.get("profile", {}).get("test"):
            continue
        target = message["target"]
        package = packages[message["manifest_path"]]
        prefix = f"{package} {target['kind'][0]}:{target['name']}"
        found.append(
            (prefix, Path(message["executable"]), Path(message["manifest_path"]).parent)
        )
    return found


def current_names() -> set[str]:
    names = set()
    for prefix, executable, package_dir in binaries():
        listed = subprocess.run(
            [str(executable), "--list", "--format", "terse"],
            cwd=package_dir,
            check=True,
            capture_output=True,
            text=True,
            env={**os.environ, "RUST_BACKTRACE": "0"},
        ).stdout
        names.update(f"{prefix} {name}" for name in parse_list(listed))
    return names


def check() -> int:
    if not LIST.exists():
        print(f"{LIST.relative_to(ROOT)} is missing: python3 scripts/test_names.py --write", file=sys.stderr)
        return 1
    os_name, recorded = parse_file(LIST.read_text(encoding="utf-8"))
    if os_name != system():
        print(f"Test inventory check skipped: the list is {os_name}'s, this is {system()}.")
        return 0
    current = current_names()
    gone, new = compare(recorded, current)
    if new:
        print(
            f"{len(new)} test(s) not in {LIST.relative_to(ROOT)} yet; "
            "python3 scripts/test_names.py --write records them."
        )
    if gone:
        print(
            f"{len(gone)} test(s) in {LIST.relative_to(ROOT)} are gone. A removed or renamed test "
            "lands with the list updated in the same change (python3 scripts/test_names.py "
            "--write):",
            file=sys.stderr,
        )
        for name in gone:
            print(f"  {name}", file=sys.stderr)
        return 1
    print(f"Test inventory: {len(current)} tests, none gone.")
    return 0


def write(other_system: bool = False) -> int:
    if system() != "darwin" and not other_system:
        print(
            f"The list is made on macOS, where the gate runs; this is {system()}. "
            "--other-system writes a list for this system instead.",
            file=sys.stderr,
        )
        return 1
    current = current_names()
    LIST.write_text(render(system(), current), encoding="utf-8")
    print(f"{LIST.relative_to(ROOT)}: {len(current)} tests ({system()}).")
    return 0


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true", help="fail when a recorded test is gone")
    mode.add_argument("--write", action="store_true", help="record the current tests (on macOS)")
    parser.add_argument(
        "--other-system",
        action="store_true",
        help="with --write: write the list on a system other than macOS",
    )
    args = parser.parse_args(argv)
    return check() if args.check else write(args.other_system)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
